    fun addOrUpdatePlant(plant: Plant) {
        val index = _customPlants.indexOfFirst { it.id == plant.id }
        if (index >= 0) {
            _customPlants[index] = plant
        } else {
            // Check if it's updating a base catalog item
            val baseIndex = baseCatalog.indexOfFirst { it.id == plant.id }
            if (baseIndex >= 0) {
                // If updating base item, add modified version to custom plants
                _customPlants.removeAll { it.id == plant.id }
                _customPlants.add(plant)
            } else {
                _customPlants.add(plant)
            }
        }
    }

